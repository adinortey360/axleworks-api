/**
 * Silent vehicle shadow-sync.
 *
 * The phone app is local-first: cars live in on-device storage and the app
 * works fully offline. Separately, the backend wants a mirror of every car
 * so shops, service records and support tooling can reference it.
 *
 * Flow:
 *   1. App creates/updates a car locally -> POST /auth/vehicles/sync
 *      (no auth needed) with a client-generated `clientId`. Idempotent:
 *      resubmits return the existing record. The record is UNLINKED
 *      (no customer) until the user has an account.
 *   2. User creates an account / logs in -> POST /auth/vehicles/link
 *      (user token) with their local clientIds. Records that are still
 *      unlinked get attached to the caller's customer.
 *
 * Everything here is pure (no mongoose, no express) so it can be
 * unit-tested without a database.
 */

export interface VehicleSyncPayload {
  clientId: string;
  make: string;
  model: string;
  year: number;
  vin?: string;
  plateNumber?: string;
  mileage?: number;
  fuelType?: string;
  nickname?: string;
}

export interface VehicleSyncDoc {
  clientId: string;
  make: string;
  model: string;
  year: number;
  vin?: string;
  licensePlate?: string;
  mileage?: number;
  fuelType?: string;
  nickname?: string;
}

function isNonEmptyString(v: unknown): v is string {
  return typeof v === 'string' && v.trim().length > 0;
}

function isRecord(v: unknown): v is Record<string, unknown> {
  return typeof v === 'object' && v !== null && !Array.isArray(v);
}

function isVin(v: unknown): boolean {
  return typeof v === 'string' && /^[A-HJ-NPR-Z0-9]{11,17}$/i.test(v.trim());
}

/**
 * Validate an unknown body for POST /auth/vehicles/sync.
 * VIN is optional (manual-entry cars may not have one) but when present
 * it must be structurally valid. clientId is required - it is the
 * idempotency key the app generates once per car.
 */
export function validateVehicleSync(body: unknown): { value?: VehicleSyncPayload; errors: string[] } {
  const errors: string[] = [];
  if (!isRecord(body)) return { errors: ['body must be a JSON object'] };

  if (!isNonEmptyString(body.clientId)) {
    errors.push('clientId is required (idempotency key generated by the app)');
  } else if (body.clientId.trim().length > 64) {
    errors.push('clientId must be at most 64 characters');
  }
  if (!isNonEmptyString(body.make)) errors.push('make is required');
  if (!isNonEmptyString(body.model)) errors.push('model is required');
  if (body.year === undefined || !Number.isInteger(Number(body.year))) {
    errors.push('year is required (integer)');
  } else {
    const year = Number(body.year);
    const thisYear = new Date().getFullYear();
    if (year < 1950 || year > thisYear + 2) errors.push(`year must be between 1950 and ${thisYear + 2}`);
  }
  if (body.vin !== undefined && body.vin !== '' && !isVin(body.vin)) {
    errors.push('vin must be an 11-17 character VIN when provided');
  }
  if (body.mileage !== undefined) {
    const m = Number(body.mileage);
    if (!Number.isFinite(m) || m < 0) errors.push('mileage must be a non-negative number');
  }
  for (const field of ['plateNumber', 'fuelType', 'nickname'] as const) {
    if (body[field] !== undefined && typeof body[field] !== 'string') {
      errors.push(`${field} must be a string`);
    }
  }

  if (errors.length > 0) return { errors };
  const value: VehicleSyncPayload = {
    clientId: (body.clientId as string).trim(),
    make: (body.make as string).trim(),
    model: (body.model as string).trim(),
    year: Number(body.year),
  };
  if (isNonEmptyString(body.vin)) value.vin = (body.vin as string).trim().toUpperCase();
  if (isNonEmptyString(body.plateNumber)) value.plateNumber = (body.plateNumber as string).trim();
  if (body.mileage !== undefined) value.mileage = Math.floor(Number(body.mileage));
  if (isNonEmptyString(body.fuelType)) value.fuelType = (body.fuelType as string).trim();
  if (isNonEmptyString(body.nickname)) value.nickname = (body.nickname as string).trim();
  return { value, errors: [] };
}

/** Map a validated sync payload onto Vehicle document fields. */
export function mapSyncToVehicleDoc(payload: VehicleSyncPayload): VehicleSyncDoc {
  const doc: VehicleSyncDoc = {
    clientId: payload.clientId,
    make: payload.make,
    model: payload.model,
    year: payload.year,
  };
  if (payload.vin !== undefined) doc.vin = payload.vin;
  if (payload.plateNumber !== undefined) doc.licensePlate = payload.plateNumber;
  if (payload.mileage !== undefined) doc.mileage = payload.mileage;
  if (payload.fuelType !== undefined) doc.fuelType = payload.fuelType;
  if (payload.nickname !== undefined) doc.nickname = payload.nickname;
  return doc;
}

/**
 * Validate POST /auth/vehicles/link. Just a non-empty list of clientIds;
 * the endpoint only attaches records that are still unlinked.
 */
export function validateVehicleLink(body: unknown): { clientIds?: string[]; errors: string[] } {
  const errors: string[] = [];
  if (!isRecord(body)) return { errors: ['body must be a JSON object'] };
  if (!Array.isArray(body.clientIds) || body.clientIds.length === 0) {
    return { errors: ['clientIds must be a non-empty array'] };
  }
  if (body.clientIds.length > 50) return { errors: ['clientIds accepts at most 50 entries'] };
  const ids = body.clientIds.filter(isNonEmptyString).map((s: string) => s.trim());
  if (ids.length !== (body.clientIds as unknown[]).length) {
    errors.push('every clientId must be a non-empty string');
  }
  if (errors.length > 0) return { errors };
  return { clientIds: [...new Set(ids)], errors: [] };
}
